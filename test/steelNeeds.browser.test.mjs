import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { buildSteelNeeds } from '../src/lib/steelNeeds.ts';

const enabled = process.env.STEEL_NEEDS_BROWSER_TEST === '1';
const base = 'http://localhost:3000';
const source = { bidBoardId: 'b1', proposalId: 'e1', estimatedHours: 100, projectManagementHours: 0, allocatableHours: 100 };
const project = { key: 'p1', projectId: 'p1', projectName: 'Warehouse', projectNumber: '100', customer: 'Customer', projectManager: '', source, issue: null, plan: { revision: 1, source, allocations: [{ month: '2026-11', percent: 100 }], notes: '', updatedBy: '', updatedAt: '2026-11-10' } };
const line = { companyId: 'company', bidBoardProjectId: 'b1', proposalId: 'e1', lineItemId: 'l1', name: "#4 Rebar - 20' Pc", uom: 'EA', quantity: 100, syncedAt: '2026-11-10T12:00:00Z', payload: {} };
const projects = buildSteelNeeds('company', [project,
  { ...project, key: 'p2', projectId: 'p2', projectName: 'School', source: { ...source, bidBoardId: 'b2' }, plan: null },
], [{ ...line, quantity: 60 }, { ...line, lineItemId: 'footer', name: '#4 Rebar 2 Continuous Footer', quantity: 40 }, { ...line, bidBoardProjectId: 'b2', name: '#4 Rebar 10 ft Wall', quantity: 50 },
  { ...line, lineItemId: 'wire', name: "Wire Mesh 6 ga (2.9x2.9 6x6) 5'x10' Sheet", quantity: 12 },
  { ...line, lineItemId: 'wire-sog', name: 'Wire Mesh 6 ga - House Keeping Pds', quantity: 8 },
  { ...line, lineItemId: 'wire-w4', name: "Wire Mesh 6x6 W4.0 W4.0 5'x10' Sheet", quantity: 10 },
  { ...line, lineItemId: 'wire-4ga', name: "Wire Mesh 4 ga 5'x10' Sheet", quantity: 5 },
  { ...line, lineItemId: 'wire-large', name: "Wire Mesh 6 ga (6x6) 8'x15' Sheet", quantity: 7 },
], [{ projectId: 'p1', dailyLogs: 2, timesheets: 3, firstActivity: '2026-11-01' }]);

test('Steel needs browser: grouping, project detail, filters, CSV, mobile and failed reload', { skip: !enabled, timeout: 120000 }, async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  let fail = false, failSave = false;
  let saveGate = null, releaseSave;
  const fixtureProjects = structuredClone(projects);
  for (const project of fixtureProjects) for (const item of project.items) item.orderSnapshot = 'fixture-snapshot';
  await page.context().addCookies([{ name: 'dev_user_email', value: 'todd@pmcdecor.com', url: base, sameSite: 'Lax' }]);
  // Refresh the signed permission cookie after adding a new page in a running dev session.
  assert.equal((await page.request.get(`${base}/api/permissions/me`)).status(), 200);
  await page.route('**/api/steel-needs', async route => {
    if (route.request().method() === 'POST') {
      const input = route.request().postDataJSON();
      if (input.projectId === 'p1' && saveGate) await saveGate;
      if (failSave) return route.fulfill({ status: 503, json: { error: 'Unable to save the order mark. Refresh saved data before retrying.' } });
      const item = fixtureProjects.find(project => project.projectId === input.projectId)?.items.find(item => item.key === input.itemKey);
      assert.ok(item); assert.equal(input.quantity, item.quantity); assert.equal(input.revision, item.order?.revision || 0);
      assert.equal(input.orderSnapshot, item.orderSnapshot);
      item.order = { revision: input.revision + 1, orderedAt: input.ordered ? '2026-11-11T02:00:00Z' : null, quantity: input.ordered ? input.orderedQuantity ?? item.quantity : null, estimateQuantity: input.ordered ? item.quantity : null };
      return route.fulfill({ json: { order: item.order } });
    }
    return route.fulfill(fail ? { status: 503, json: { error: 'Unable to load Steel needs.' } } : { json: { projects: fixtureProjects, loadedAt: '2026-11-10T12:00:00Z', localOnly: false } });
  });
  try {
    await page.goto(`${base}/steel-needs`, { waitUntil: 'networkidle' });
    const worksheet = page.getByRole('table', { name: 'Steel order worksheet', exact: true });
    const worksheetRebar = worksheet.getByRole('row').filter({ has: page.locator('summary').filter({ hasText: line.name }) });
    const worksheetValues = () => worksheetRebar.getByRole('cell').evaluateAll(cells => cells.slice(1).map(cell => cell.firstChild?.textContent));
    await worksheet.waitFor();
    assert.deepEqual(await worksheetValues(), ['EA', '150', '0', '150', '2']);
    await worksheetRebar.getByText('150 pcs / bundle', { exact: true }).waitFor();
    await worksheetRebar.getByRole('cell').nth(4).getByText('1 whole bundle', { exact: false }).waitFor();
    await page.getByLabel('Order list', { exact: true }).selectOption('ordered');
    await page.getByText('No materials marked ordered in this scope.', { exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Export order worksheet' }).isDisabled(), true);
    await page.getByLabel('Order list', { exact: true }).selectOption('all');
    await page.getByRole('button', { name: 'By description', exact: true }).click();
    const table = page.getByRole('table', { name: 'Steel totals by description', exact: true });
    await table.waitFor();
    const smallWire = table.getByRole('row').filter({ has: page.getByRole('button', { name: /Wire Mesh 6 ga 5'x10'$/ }) });
    assert.equal(await smallWire.count(), 1);
    assert.equal(await smallWire.getByRole('cell').nth(4).innerText(), '20');
    const fourGauge = table.getByRole('row').filter({ has: page.getByRole('button', { name: /Wire Mesh 4 ga 5'x10'$/ }) });
    assert.equal(await fourGauge.getByRole('cell').nth(4).innerText(), '15');
    await table.getByRole('button', { name: /Wire Mesh 6 ga 8'x15'$/ }).waitFor();
    assert.doesNotMatch(await table.innerText(), /2.9x2.9|6x6|SOG|House Keeping|W4\.0/);
    await table.getByRole('button', { name: /#4 Rebar/ }).click();
    const detail = page.getByRole('table', { name: `Projects for ${line.name}`, exact: true });
    assert.match(await detail.innerText(), /Warehouse/); assert.match(await detail.innerText(), /School/);
    const warehouseMark = page.getByRole('checkbox', { name: `Ordered ${line.name} for Warehouse`, exact: true });
    const schoolMark = page.getByRole('checkbox', { name: `Ordered ${line.name} for School`, exact: true });
    saveGate = new Promise(resolve => { releaseSave = resolve; });
    await warehouseMark.click();
    // A deliberately held save must show the requested check immediately, without blocking another project.
    assert.equal(await warehouseMark.isChecked(), true);
    assert.equal(await warehouseMark.isDisabled(), true);
    await detail.getByText('Saving…', { exact: true }).waitFor();
    const descriptionRebar = table.getByRole('row').filter({ has: page.getByRole('button', { name: /#4 Rebar/ }) });
    assert.match(await descriptionRebar.getByRole('cell').nth(6).innerText(), /^0/);
    assert.equal(await descriptionRebar.getByRole('cell').nth(7).evaluate(cell => cell.firstChild.textContent), '150');
    assert.equal(await schoolMark.isEnabled(), true);
    assert.equal(await page.getByRole('button', { name: 'Refresh saved data' }).isDisabled(), true);
    assert.equal(await page.getByRole('button', { name: 'Export order worksheet' }).isDisabled(), true);
    await schoolMark.click();
    const schoolRow = detail.getByRole('row').filter({ has: schoolMark });
    await schoolRow.getByText('Updated 11/10/2026', { exact: true }).waitFor();
    assert.equal(await schoolMark.isChecked(), true);
    assert.equal(await warehouseMark.isDisabled(), true);
    await schoolMark.click();
    await schoolRow.getByText('Saving…', { exact: true }).waitFor({ state: 'detached' });
    saveGate = null; releaseSave();
    await detail.getByRole('row').filter({ has: warehouseMark }).getByText('Updated 11/10/2026', { exact: true }).waitFor();
    assert.equal(await warehouseMark.isChecked(), true);
    assert.equal(await page.getByRole('checkbox', { name: `Ordered ${line.name} for School`, exact: true }).isChecked(), false);
    await page.getByRole('button', { name: 'Order worksheet', exact: true }).click();
    assert.deepEqual(await worksheetValues(), ['EA', '150', '100', '50', '2']);
    await page.getByLabel('Order list', { exact: true }).selectOption('ordered');
    assert.deepEqual(await worksheetValues(), ['EA', '100', '1']);
    const [orderedDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export order worksheet' }).click()]);
    const orderedCsv = await readFile(await orderedDownload.path(), 'utf8');
    assert.equal(orderedCsv.split('\r\n').length, 2);
    assert.match(orderedCsv, /"EA","100"/); assert.match(orderedCsv, /"Pieces per bundle","Ordered bundle equivalents"/); assert.match(orderedCsv, /"150","0.6667"/); assert.match(orderedCsv, /Warehouse/); assert.doesNotMatch(orderedCsv, /School/);
    await page.getByLabel('Order list', { exact: true }).selectOption('needed');
    assert.deepEqual(await worksheetValues(), ['EA', '50', '1']);
    await worksheetRebar.getByRole('cell').nth(2).getByText('150 pcs · 100 extra', { exact: true }).waitFor();
    await worksheetRebar.locator('summary').click();
    assert.match(await worksheetRebar.innerText(), /School/); assert.doesNotMatch(await worksheetRebar.innerText(), /Warehouse/);
    await page.reload({ waitUntil: 'networkidle' });
    await page.getByRole('button', { name: 'By description', exact: true }).click();
    await table.getByRole('button', { name: /#4 Rebar/ }).click();
    await detail.getByText('Updated 11/10/2026', { exact: true }).waitFor();
    assert.equal(await warehouseMark.isChecked(), true);
    await page.getByLabel('Project status', { exact: true }).selectOption('not-started');
    assert.equal(await table.getByRole('button', { name: /Wire Mesh/ }).count(), 0);
    await table.getByText('50', { exact: true }).first().waitFor();
    const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export order worksheet' }).click()]);
    const csv = await readFile(await download.path(), 'utf8');
    assert.match(csv, /School/); assert.doesNotMatch(csv, /Warehouse/); assert.match(csv, /"50"/);
    await page.getByLabel('Planned start through', { exact: true }).fill('2026-11');
    await page.getByText('No steel quantities match these filters.', { exact: false }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Export order worksheet' }).isDisabled(), true);
    await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
    await page.getByRole('button', { name: 'By project', exact: true }).click();
    await page.locator('summary').filter({ hasText: 'Warehouse' }).click();
    await page.getByRole('table', { name: 'Steel for Warehouse', exact: true }).waitFor();
    assert.equal(await warehouseMark.isChecked(), true);
    await warehouseMark.click();
    await page.getByText('Saving…', { exact: true }).waitFor({ state: 'detached' });
    await page.getByRole('table', { name: 'Steel for Warehouse', exact: true }).getByText('Updated 11/10/2026', { exact: true }).waitFor({ state: 'detached' });
    assert.equal(await warehouseMark.isChecked(), false);
    failSave = true;
    saveGate = new Promise(resolve => { releaseSave = resolve; });
    await warehouseMark.click();
    assert.equal(await warehouseMark.isChecked(), true);
    await page.getByText('Saving…', { exact: true }).waitFor();
    saveGate = null; releaseSave();
    await page.getByRole('alert').filter({ hasText: 'Unable to save the order mark.' }).waitFor();
    assert.equal(await warehouseMark.isChecked(), false);
    failSave = false;
    await page.getByText('2 daily-log entries · 3 timesheet entries', { exact: false }).waitFor();
    await page.getByLabel('Search description or project', { exact: true }).fill('School');
    assert.equal(await page.locator('summary').filter({ hasText: 'Warehouse' }).count(), 0);
    await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
    await page.getByRole('button', { name: 'Order worksheet', exact: true }).click();
    assert.deepEqual(await worksheetValues(), ['EA', '150', '0', '150', '2']);
    await worksheetRebar.locator('summary').click();
    await warehouseMark.click();
    await worksheetRebar.getByText('Updated 11/10/2026', { exact: true }).waitFor();
    assert.deepEqual(await worksheetValues(), ['EA', '150', '100', '50', '2']);
    const piecesInput = page.getByRole('spinbutton', { name: `Ordered pieces for ${line.name} for Warehouse`, exact: true });
    const savePieces = page.getByRole('button', { name: `Save ordered quantity for ${line.name} for Warehouse`, exact: true });
    await piecesInput.fill('30');
    await savePieces.click();
    await worksheetRebar.getByText('Partially ordered · 70 pieces still needed', { exact: true }).waitFor();
    assert.equal(await warehouseMark.isChecked(), false);
    assert.equal(await warehouseMark.evaluate(element => element.indeterminate), true);
    assert.deepEqual(await worksheetValues(), ['EA', '150', '30', '120', '2']);
    assert.doesNotMatch(await worksheetRebar.innerText(), /Estimate changed/);
    await page.reload({ waitUntil: 'networkidle' });
    await worksheetRebar.locator('summary').click();
    assert.equal(await piecesInput.inputValue(), '30');
    await piecesInput.fill('60');
    await savePieces.click();
    await worksheetRebar.getByText('Partially ordered · 40 pieces still needed', { exact: true }).waitFor();
    assert.deepEqual(await worksheetValues(), ['EA', '150', '60', '90', '2']);
    failSave = true;
    await piecesInput.fill('80');
    await savePieces.click();
    await page.getByRole('alert').filter({ hasText: 'Unable to save the order mark.' }).waitFor();
    assert.deepEqual(await worksheetValues(), ['EA', '150', '60', '90', '2']);
    failSave = false;
    await piecesInput.fill('0');
    await savePieces.click();
    await page.getByText('Saving…', { exact: true }).waitFor({ state: 'detached' });
    assert.deepEqual(await worksheetValues(), ['EA', '150', '0', '150', '2']);
    await piecesInput.fill('30');
    await savePieces.click();
    await worksheetRebar.getByText('Partially ordered · 70 pieces still needed', { exact: true }).waitFor();
    await mkdir('outputs/steel-needs', { recursive: true });
    await page.evaluate(() => { window.scrollTo(0, 0); });
    await page.screenshot({ path: 'outputs/steel-needs/desktop-fixture.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'no page-level overflow');
    await page.screenshot({ path: 'outputs/steel-needs/mobile-fixture.png', fullPage: true });
    fail = true;
    await page.getByRole('button', { name: 'Refresh saved data' }).click();
    await page.getByRole('alert').filter({ hasText: 'Unable to load Steel needs.' }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Export order worksheet' }).isDisabled(), true);
    assert.equal(await table.count(), 0);
    assert.equal(await worksheet.count(), 0);
    assert.deepEqual(errors, []);
  } finally { releaseSave?.(); await browser.close(); }
});
