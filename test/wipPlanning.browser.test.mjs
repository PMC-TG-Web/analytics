import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import http from 'node:http';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { chromium } from 'playwright-core';

test('PM edits month cells, retains hidden months and notes, and scrolls the grid from the top', { skip: process.env.WIP_BROWSER_TEST !== '1', timeout: 90_000 }, async () => {
  const require = createRequire(import.meta.url);
  const esbuild = require(process.env.WIP_TEST_ESBUILD || path.join(process.env.APPDATA, 'npm/node_modules/netlify-cli/node_modules/esbuild/lib/main.js'));
  const postcss = require('postcss');
  const tailwind = require('@tailwindcss/postcss');
  const entry = `import React from 'react';import{createRoot}from'react-dom/client';import Page from ${JSON.stringify(path.resolve('src/app/wip/page.tsx'))};createRoot(document.getElementById('root')).render(<Page/>);`;
  const built = await esbuild.build({ stdin: { contents: entry, resolveDir: process.cwd(), loader: 'tsx' }, write: false, bundle: true, platform: 'browser', format: 'iife', jsx: 'automatic', alias: { '@': path.resolve('src') }, define: { 'process.env.NODE_ENV': '"test"' } });
  const stylesheet = await postcss([tailwind()]).process(readFileSync('src/app/globals.css', 'utf8'), { from: path.resolve('src/app/globals.css') });
  const server = http.createServer((req, res) => {
    res.setHeader('content-type', req.url === '/bundle.js' ? 'application/javascript' : req.url === '/style.css' ? 'text/css' : 'text/html');
    res.end(req.url === '/bundle.js' ? built.outputFiles[0].text : req.url === '/style.css' ? stylesheet.css : '<html><head><link rel="stylesheet" href="/style.css"></head><body><div id="root"></div><script src="/bundle.js"></script></body></html>');
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  let browser;
  try {
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [], posts = [];
    page.on('pageerror', error => errors.push(error.message));
    const source = { bidBoardId: '11', proposalId: '22', estimatedHours: 1200, projectManagementHours: 200, allocatableHours: 1000 };
    let plan = null, conflict = false, estimateChanged = false;
    const fillerProjects = Array.from({ length: 42 }, (_, index) => ({ key: String(102 + index), projectId: String(102 + index), projectName: `Project ${index + 2}`, projectNumber: String(2602 + index), projectManager: 'PM Two', customer: 'Example customer', source, fingerprint: 'current', issue: null, plan: null }));
    await page.route('**/api/wip*', async route => {
      if (route.request().method() === 'POST') {
        posts.push(route.request().postDataJSON());
        if (conflict) return route.fulfill({ status: 409, json: { error: 'Another user saved this plan. Reload before saving your changes.' } });
        const body = posts.at(-1);
        plan = { revision: body.revision + 1, source: estimateChanged ? { ...source, estimatedHours: 1600, allocatableHours: 1400 } : source, allocations: body.allocations, notes: body.notes, updatedBy: 'pm@example.com', updatedAt: '2026-10-12T16:00:00Z' };
        return route.fulfill({ json: { plan } });
      }
      if (new URL(route.request().url()).searchParams.has('projectId')) return route.fulfill({ json: { history: [{ ...plan, createdBy: plan.updatedBy, createdAt: plan.updatedAt }] } });
      return route.fulfill({ json: { projects: [{ key: '101', projectId: '101', projectName: 'Project X', projectNumber: '2601', projectManager: 'PM One, PM Three', projectManagers: [{ id: 'pm1', name: 'PM One' }, { id: 'pm3', name: 'PM Three' }], customer: 'Example customer', source: estimateChanged ? { ...source, estimatedHours: 1600, allocatableHours: 1400 } : source, fingerprint: estimateChanged ? 'updated' : 'current', issue: null, plan }, ...fillerProjects] } });
    });
    await page.goto(origin);
    await page.getByLabel('24 months starting').fill('2026-10');
    assert.equal(await page.locator('thead th').count(), 27);
    assert.equal(await page.locator('thead th').last().innerText(), 'Sep 2028');
    const row = page.getByRole('row', { name: 'Project X', exact: true });
    const cell = month => page.getByRole('textbox', { name: `Project X, ${month} percentage`, exact: true });
    const save = page.getByRole('button', { name: 'Save Project X', exact: true });
    const cancel = page.getByRole('button', { name: 'Cancel changes for Project X', exact: true });
    const notes = page.getByRole('textbox', { name: 'Planning notes for Project X', exact: true });
    await cell('Oct 2026').fill('40');
    assert.equal(await save.isDisabled(), true);
    await cell('Nov 2026').fill('40');
    await cell('Jan 2027').fill('20');
    await row.locator('summary').filter({ hasText: /^Planning notes/ }).click();
    await notes.fill('January work after the holiday break.');
    assert.equal(await save.isDisabled(), false);
    assert.equal(await page.getByRole('button', { name: '+ Add month', exact: true }).count(), 0);
    await save.click();
    await page.getByRole('status').filter({ hasText: 'Saved Project X' }).waitFor();
    assert.deepEqual(posts[0].allocations, [{ month: '2026-10', percent: 40 }, { month: '2026-11', percent: 40 }, { month: '2027-01', percent: 20 }]);
    assert.ok(await page.getByText('400 h', { exact: true }).count() >= 2);
    assert.ok(await page.getByText('200 h', { exact: true }).count() >= 1);

    // Long-list scrolling is independent of the page; both horizontal bars agree.
    const grid = page.getByRole('region', { name: 'WIP allocation grid', exact: true });
    const topScroll = page.getByRole('region', { name: 'Scroll months horizontally', exact: true });
    assert.ok(await grid.evaluate(element => element.scrollHeight > element.clientHeight * 3));
    const header = grid.locator('thead th').first();
    const originalHeader = await header.boundingBox();
    await topScroll.evaluate(element => { element.scrollLeft = 300; });
    await page.waitForFunction(() => document.querySelector('[aria-label="WIP allocation grid"]').scrollLeft === 300);
    await grid.evaluate(element => { element.scrollTop = 1200; });
    const scrolledHeader = await header.boundingBox();
    assert.ok(Math.abs(originalHeader.y - scrolledHeader.y) < 2, 'month headings remain fixed vertically');
    assert.ok(Math.abs(originalHeader.x - scrolledHeader.x) < 2, 'project column remains fixed horizontally');
    const topBox = await topScroll.boundingBox();
    assert.ok(topBox.height >= 16, 'top scrollbar has a usable visible height');
    assert.ok(topBox.y >= 0 && topBox.y + topBox.height < 1000, 'top scrollbar is visible without reaching the last job');
    const footerBox = await grid.locator('tfoot td').first().boundingBox();
    const gridBox = await grid.boundingBox();
    assert.ok(footerBox.y + footerBox.height <= gridBox.y + gridBox.height + 2, 'workload totals remain in the table viewport');
    await grid.evaluate(element => { element.scrollLeft = 250; });
    await page.waitForFunction(() => document.querySelector('[aria-label="Scroll months horizontally"]').scrollLeft === 250);
    await grid.evaluate(element => { element.scrollTop = 0; element.scrollLeft = 0; });
    await page.waitForFunction(() => document.querySelector('[aria-label="Scroll months horizontally"]').scrollLeft === 0);
    await page.getByRole('button', { name: 'Scroll months right', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[aria-label="WIP allocation grid"]').scrollLeft > 300);
    await page.getByRole('button', { name: 'Scroll months left', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[aria-label="WIP allocation grid"]').scrollLeft === 0);
    if (process.env.WIP_SCREENSHOT) await page.screenshot({ path: process.env.WIP_SCREENSHOT, fullPage: true });

    await page.reload();
    await page.getByLabel('24 months starting').fill('2027-01');
    assert.equal(await cell('Jan 2027').inputValue(), '20');
    await cell('Jan 2027').fill('30');
    assert.equal(await save.isDisabled(), true, 'hidden October/November still count toward the total');
    await page.getByLabel('24 months starting').fill('2026-10');
    assert.equal(await cell('Oct 2026').inputValue(), '40');
    assert.equal(await cell('Nov 2026').inputValue(), '40');
    await cell('Nov 2026').fill('');
    await cell('Oct 2026').fill('70');
    assert.equal(await save.isDisabled(), false);
    await save.click();
    await page.getByRole('status').filter({ hasText: 'Saved Project X' }).waitFor();
    assert.deepEqual(posts[1].allocations, [{ month: '2026-10', percent: 70 }, { month: '2027-01', percent: 30 }]);
    assert.equal(posts[1].notes, 'January work after the holiday break.');
    await cell('Oct 2026').fill('0');
    assert.equal(await save.isDisabled(), true);
    await cancel.click();
    assert.equal(await cell('Oct 2026').inputValue(), '70');

    // Different project drafts coexist and cannot disappear through filtering.
    await cell('Oct 2026').fill('60');
    await page.getByRole('textbox', { name: 'Project 2, Oct 2026 percentage', exact: true }).fill('50');
    await cancel.click();
    assert.equal(await page.getByLabel('Find a job').isDisabled(), true);
    await page.getByRole('button', { name: 'Cancel changes for Project 2', exact: true }).click();
    assert.equal(await page.getByLabel('Find a job').isDisabled(), false);
    await row.locator('summary').filter({ hasText: /^Planning notes/ }).click();
    await page.getByRole('button', { name: 'View revision history', exact: true }).click();
    await page.getByText(/Revision 2/).waitFor();
    conflict = true;
    await notes.fill('Keep my unsaved update.');
    await save.click();
    await page.getByRole('alert').filter({ hasText: 'Another user saved' }).waitFor();
    assert.equal(await notes.inputValue(), 'Keep my unsaved update.');
    assert.equal(await page.getByRole('button', { name: 'Refresh', exact: true }).isDisabled(), true);
    await cancel.click();
    conflict = false; estimateChanged = true;
    await page.getByRole('button', { name: 'Refresh', exact: true }).click();
    await row.getByText(/Use updated estimate/).waitFor();
    await cell('Oct 2026').fill('60');
    await cell('Jan 2027').fill('40');
    assert.equal(await save.isDisabled(), true, 'changed estimate still requires review');
    await row.getByRole('checkbox').check();
    await save.click();
    await page.getByRole('status').filter({ hasText: 'Saved Project X' }).waitFor();
    assert.equal(posts.at(-1).fingerprint, 'updated');
    await page.getByRole('combobox', { name: /^Project Manager/ }).selectOption('PM Three');
    assert.equal(await page.locator('tbody tr').count(), 1, 'a job with multiple Paradise PMs matches each individual PM');
    await page.getByRole('combobox', { name: /^Project Manager/ }).selectOption('');
    await page.getByLabel('Find a job').fill('No match');
    await page.getByText('No jobs match these filters.', { exact: true }).waitFor();
    assert.deepEqual(errors, []);
  } finally {
    await browser?.close();
    await new Promise(resolve => server.close(resolve));
  }
});
