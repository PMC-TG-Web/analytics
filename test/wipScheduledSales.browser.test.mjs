import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import http from 'node:http';
import { createRequire } from 'node:module';
import { chromium } from 'playwright-core';

test('KPI shows read-only WIP revenue by year, refreshes on return, and recovers from errors', { skip: process.env.WIP_BROWSER_TEST !== '1', timeout: 60_000 }, async () => {
  const require = createRequire(import.meta.url);
  const esbuild = require(process.env.WIP_TEST_ESBUILD || path.join(process.env.APPDATA, 'npm/node_modules/netlify-cli/node_modules/esbuild/lib/main.js'));
  const entry = `import React,{useState}from'react';import{createRoot}from'react-dom/client';import Row,{useWipScheduledSales}from ${JSON.stringify(path.resolve('src/components/KpiScheduledSalesRow.tsx'))};function App(){const data=useWipScheduledSales();const[year,setYear]=useState('2026');const years=year?[year]:['2026','2027'];return <><select aria-label="Year" value={year} onChange={e=>setYear(e.target.value)}><option value="">All Years</option><option>2026</option><option>2027</option></select><table><tbody><Row data={data} onDetails={(year,month)=>{window.details={year,month}}} months={years.flatMap(year=>Array.from({length:12},(_,i)=>({year,month:i+1})))}/></tbody></table></>}createRoot(document.getElementById('root')).render(<App/>);`;
  const built = await esbuild.build({ stdin: { contents: entry, resolveDir: process.cwd(), loader: 'tsx' }, write: false, bundle: true, platform: 'browser', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"test"' } });
  const server = http.createServer((req, res) => {
    res.setHeader('content-type', req.url === '/bundle.js' ? 'application/javascript' : 'text/html');
    res.end(req.url === '/bundle.js' ? built.outputFiles[0].text : '<html><body><div id="root"></div><script src="/bundle.js"></script></body></html>');
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage();
    let failed = false, october = 400.25;
    let unscheduledProjects = [{ id: 'p1', projectId: 'p1', projectName: 'Project awaiting allocation', projectNumber: '2601', customer: 'Example customer', hours: 1000, status: 'Needs allocation', reason: 'No saved WIP allocation.' },
      { id: 'p2', projectId: 'p2', projectName: 'Imported project', projectNumber: '2602', customer: 'Example customer', hours: 250.4, status: 'Import needs review', reason: 'Imported percentages need review and a saved 100% allocation.' }];
    const methods = [], errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/kpi/scheduled-sales', route => {
      methods.push(route.request().method());
      return route.fulfill(failed ? { status: 503, json: { error: 'Scheduled revenue is unavailable. Please retry.' } } : { json: { data: { months: { '2026-10': october, '2026-11': 400, '2027-01': 200 }, years: ['2026','2027'], planCount: 1, excludedDraftCount: 1, localOnly: true, unscheduledProjects } } });
    });
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    const row = page.getByRole('row', { name: 'Scheduled', exact: true });
    const month = date => row.locator(`td[title="WIP revenue · ${date}"]`);
    await month('2026-10').waitFor();
    assert.equal(await month('2026-10').innerText(), '$400');
    assert.equal(await month('2026-01').innerText(), '$0');
    assert.equal(await row.locator('td').last().innerText(), '$800');
    const summary = page.locator('summary').filter({ hasText: 'Not scheduled' });
    const pending = page.getByRole('region', { name: 'Projects not scheduled' });
    assert.equal(await summary.innerText(), 'Not scheduled (2 projects)');
    assert.equal(await pending.isVisible(), false);
    await summary.click();
    await pending.getByText('Project awaiting allocation').waitFor();
    assert.equal(await pending.getByText('1,000', { exact: true }).count(), 1);
    assert.equal(await pending.getByText('Import needs review').count(), 1);
    assert.equal(await pending.getByRole('link', { name: 'Open WIP' }).getAttribute('href'), '/wip');
    const hoursTotal = pending.getByRole('row', { name: 'Unscheduled hours total', exact: true });
    assert.equal(await hoursTotal.locator('td').first().innerText(), '1,250.4');
    assert.equal(await hoursTotal.getByRole('rowheader').innerText(), 'Total unscheduled hours');
    assert.equal(await pending.locator('table > tfoot').getByRole('row').count(), 1);
    const scheduledBox = await row.boundingBox(), summaryBox = await summary.boundingBox();
    assert.ok(summaryBox.y >= scheduledBox.y + scheduledBox.height - 1, 'the dropdown appears below Scheduled');
    if (process.env.WIP_SCREENSHOT) await page.screenshot({ path: process.env.WIP_SCREENSHOT, fullPage: true });
    await month('2026-10').getByRole('button').click();
    assert.deepEqual(await page.evaluate(() => window.details), { year: '2026', month: 10 });
    await row.locator('td').last().getByRole('button').click();
    assert.deepEqual(await page.evaluate(() => window.details), { year: '2026', month: null });
    await month('2026-10').dblclick();
    assert.equal(await row.locator('input').count(), 0);
    await page.getByLabel('Year').selectOption('2027');
    assert.equal(await month('2027-01').innerText(), '$200');
    assert.equal(await summary.innerText(), 'Not scheduled (2 projects)', 'unscheduled projects remain visible across report years');
    assert.equal(await hoursTotal.locator('td').first().innerText(), '1,250.4');
    assert.equal(await row.locator('td').last().innerText(), '$200');
    await page.getByLabel('Year').selectOption('');
    assert.equal(await row.locator('td').count(), 25);
    assert.equal(await row.locator('td').last().innerText(), '$1,000');
    october = 500;
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    await page.waitForFunction(() => document.querySelector('td[title="WIP revenue · 2026-10"]')?.textContent === '$500');
    assert.equal(await row.locator('td').last().innerText(), '$1,100');
    unscheduledProjects = [{ ...unscheduledProjects[0] }, { ...unscheduledProjects[1], hours: null, status: 'Needs source review' }];
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    await hoursTotal.getByText('Total incomplete · 1 project has missing hours', { exact: true }).waitFor();
    assert.equal(await hoursTotal.locator('td').first().innerText(), '1,000');
    assert.equal(await hoursTotal.getByRole('rowheader').innerText(), 'Known unscheduled hours');
    unscheduledProjects = [unscheduledProjects[1]];
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    await page.waitForFunction(() => document.querySelector('summary')?.textContent === 'Not scheduled (1 project)');
    assert.equal(await hoursTotal.locator('td').first().innerText(), '—', 'unknown hours do not become a zero total');
    unscheduledProjects = [];
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    await page.waitForFunction(() => document.querySelector('summary')?.textContent === 'Not scheduled (0 projects)');
    await pending.getByText('All current In Progress projects have saved WIP allocations.', { exact: true }).waitFor();
    assert.equal(await pending.getByText('Project awaiting allocation').count(), 0);
    assert.equal(await hoursTotal.count(), 0, 'the empty list does not retain an old total');
    failed = true;
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    await row.getByRole('status').waitFor();
    assert.match(await row.innerText(), /unavailable/);
    assert.equal(await row.locator('td[title^="WIP revenue"]').count(), 0, 'failed refresh does not present stale totals as current');
    assert.equal(await summary.count(), 0, 'a failed refresh does not show a stale unscheduled list');
    failed = false;
    await row.getByRole('button', { name: 'Retry' }).click();
    await month('2026-10').waitFor();
    assert.equal(await month('2026-10').innerText(), '$500');
    assert.ok(methods.length >= 4);
    assert.ok(methods.every(method => method === 'GET'));
    assert.deepEqual(errors, []);
  } finally {
    await browser?.close();
    await new Promise(resolve => server.close(resolve));
  }
});
